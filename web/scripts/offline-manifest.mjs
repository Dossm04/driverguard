import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

function walk(root) {
  return readdirSync(root, { withFileTypes: true }).flatMap((entry) => {
    const path = join(root, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  });
}
function asset(file, url) {
  const bytes = readFileSync(file);
  return { url, bytes: bytes.length, sha256: createHash("sha256").update(bytes).digest("hex") };
}
// Include dynamic chunks too: visiting a page does not load every camera dependency.
const assets = walk(".next/static").map((file) => asset(file, `/_next/static/${relative(".next/static", file).replaceAll("\\", "/")}`));
const missing = [];
for (const name of ["face_landmarker.task", "hand_landmarker.task"]) {
  const file = `public/models/${name}`;
  if (!existsSync(file)) missing.push(name);
  else assets.push(asset(file, `/models/${name}`));
}
for (const file of walk("node_modules/@mediapipe/tasks-vision/wasm")) {
  if (/\.(wasm|js)$/.test(file)) assets.push(asset(file, `/mediapipe/wasm/${relative("node_modules/@mediapipe/tasks-vision/wasm", file).replaceAll("\\", "/")}`));
}
for (const file of walk("public/icons")) assets.push(asset(file, `/icons/${relative("public/icons", file).replaceAll("\\", "/")}`));
// Generated by app/manifest.ts, served as a Next route rather than a public file.
assets.push({ url: "/manifest.webmanifest", bytes: 0 });
const manifest = { version: readFileSync(".next/BUILD_ID", "utf8").trim(), assets, missing };
writeFileSync("public/offline-assets.json", JSON.stringify(manifest));
console.log(`Offline inventory: ${assets.length} files, ${(assets.reduce((n, a) => n + a.bytes, 0) / 1024 / 1024).toFixed(1)} MB; missing: ${missing.join(", ") || "none"}`);
